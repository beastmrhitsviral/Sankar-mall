export function getSectionBySlug(slug: string): Section | undefined {
  return SECTIONS.find((s) => s.slug === slug);
}

export function getProductsBySection(products: Product[], slug: string): Product[] {
  if (slug === 'all') return products;
  return products.filter((p) => p.sectionSlug === (slug as SectionSlug));
}

export function searchProducts(products: Product[], query: string): Product[] {
  const raw = query.trim().toLowerCase();
  if (!raw) return [];
  const normalizedQuery = raw.replace(/[-_&]+/g, ' ').replace(/\s+/g, ' ').trim();
  const tokens = normalizedQuery.split(' ').filter((t) => t.length > 0);
  if (tokens.length === 0) return [];

  const sectionMap = new Map(
    SECTIONS.map((s) => [s.slug, `${s.name} ${s.description}`.toLowerCase()])
  );

  const scored: { product: Product; score: number }[] = [];
  for (const p of products) {
    const sectionText = sectionMap.get(p.sectionSlug) || '';
    const haystack = [
      p.name,
      p.brand,
      p.sectionSlug.replace(/-/g, ' '),
      sectionText,
      p.unit,
      p.description,
      ...p.highlights,
    ]
      .join(' ')
      .toLowerCase();

    const nameLower = p.name.toLowerCase();
    const brandLower = p.brand.toLowerCase();

    let score = 0;
    if (nameLower.includes(normalizedQuery)) score += 100;
    else if (brandLower.includes(normalizedQuery)) score += 60;
    else if (haystack.includes(normalizedQuery)) score += 45;

    const allTokensMatch = tokens.every((t) => haystack.includes(t));
    if (allTokensMatch) {
      score += 35;
    } else {
      let matchedTokens = 0;
      for (const t of tokens) {
        if (t.length >= 2 && haystack.includes(t)) {
          matchedTokens++;
        }
      }
      if (matchedTokens > 0) {
        score += matchedTokens * 12;
      }
    }

    if (score > 0) {
      scored.push({ product: p, score });
    }
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.map((entry) => entry.product);
}
